/** Pick a random bank question matching category + difficulty, with graceful fallbacks. */
export function pickBankQuestion(
  category: CategoryKey,
  difficulty: DifficultyKey,
): BankQuestion {
  const exact = QUESTION_BANK.filter(
    (q) => q.category === category && q.difficulty === difficulty,
  );
  const byCategory = QUESTION_BANK.filter((q) => q.category === category);
  const pool = exact.length > 0 ? exact : byCategory.length > 0 ? byCategory : QUESTION_BANK;
  return pool[Math.floor(Math.random() * pool.length)];
}
